import webbrowser
import time
import pyautogui
import urllib.parse

# ==========================================
# 1. قائمة الأرقام (ضع الأرقام هنا بين الفواصل)
# يجب أن تكون الارقام بصيغة دولية (966) بدون +
# ==========================================
phone_numbers = [
    # "966500000000",
    # "966500000001",
]

# ==========================================
# 2. نص الرسالة
# ==========================================
message = """السلام عليكم،
نؤكد قبول تسجيلكم في جلسة قوقل ونتطلع لحضوركم ومشاركتكم الفعالة.

تنويه: الالتزام بالحضور بعد التسجيل مهم، حيث أن الانسحاب يؤثر على فرص القبول في الفعاليات القادمة."""

# ==========================================
# 3. تشفير الرسالة والبدء
# ==========================================
encoded_message = urllib.parse.quote(message)

print(f"سيتم الإرسال لـ {len(phone_numbers)} شخص...")
print("سيبدأ العمل بعد 5 ثوانٍ... اترك الماوس!")
time.sleep(5) 

for number in phone_numbers:
    # فتح رابط الواتساب
    url = f"https://web.whatsapp.com/send?phone={number}&text={encoded_message}"
    webbrowser.open(url)
    
    # انتظار تحميل الصفحة (زد الرقم اذا النت بطيء)
    time.sleep(8) 
    
    # ضغط زر Enter للإرسال
    pyautogui.press('enter')
    
    # انتظار بسيط للتأكد من خروج الرسالة
    time.sleep(2)
    
    # إغلاق التبويب الحالي (Ctrl + W)
    pyautogui.hotkey('ctrl', 'w')
    
    print(f"تم الإرسال لـ {number}")

print("انتهت المهمة!")